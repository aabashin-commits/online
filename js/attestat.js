// attestat.js — блок «Аттестат государственного образца»: документ открывается
// по нажатию в увеличенном виде (ТЗ 06.09.2026, §7).
//
// ⚠️ 07.09.2026 файл переписан почти с нуля. Раньше он рисовал пять вкладок
// («Аттестат гос. образца», «Группа до 12 человек», «Прогресс под контролем»,
// «Удобный формат», «Уроки в записи») из массива данных: JS подменял заголовок,
// лид, примечание, картинку и бабблы. ТЗ вкладки убрало — в секции остаётся
// только аттестат, а темы остальных вкладок разошлись по блокам «Ключевые
// преимущества» и «Как проходит учебный день».
//
// Тексты старых вкладок не переносим намеренно: вкладка «Удобный формат»
// раскрывала запрещённое §3 ТЗ — периодичность аттестаций, дистанционный
// порядок их прохождения, выдачу аттестата школой-партнёром и справки
// об обучении. Всё это теперь звучит только на консультации.
//
// Лайтбокс не свой: используем общий window.openLightbox() из main.js — тот же,
// что открывает видеоотзывы. Он сам блокирует скролл, ставит фокус на кнопку
// закрытия и возвращает его обратно при закрытии.
(() => {
  'use strict';

  const root = document.querySelector('.attestat');
  if (!root) return;

  const frame = root.querySelector('.attestat__frame');
  const img = root.querySelector('.attestat__img');
  if (!frame || !img || typeof window.openLightbox !== 'function') return;

  frame.addEventListener('click', () => {
    const large = document.createElement('img');
    // currentSrc — то, что браузер реально выбрал из <picture>: на телефоне
    // это мобильный коллаж, на десктопе широкий. src отдал бы всегда десктопный.
    large.src = img.currentSrc || img.src;
    large.alt = img.alt;
    large.className = 'attestat__lightbox-img';
    window.openLightbox(large, 'Аттестат государственного образца');
  });
})();
