// bitrix.js — все CTA-кнопки страницы открывают CRM-форму Битрикс24 (тип «click»).
//
// О номере формы файл ничего не знает: он ищет скрытую кнопку .b24-trigger и кликает
// по ней. Номер стоит в разметке index.html — сейчас это click/225/yn061r.
// ⚠️ TODO: форма скопирована с офлайн-сайта, у онлайн-школы должна быть своя —
// в текущей заявка приходит с выбором московского филиала. Получить у клиента ID
// формы онлайн-школы и заменить в index.html в ДВУХ местах: у <script>-лоадера
// (там же номер loader_NNN.js) и у скрытой кнопки .b24-trigger.
//
// Кнопки ведут заявку через общий хелпер window.openForm() (см. main.js: делегированный
// клик по [data-open-form]). Раньше его переопределял form.js и открывал кастомную модалку.
// Здесь мы переопределяем openForm ПОСЛЕ form.js (порядок подключения в index.html): вместо
// модалки имитируем клик по скрытому элементу-триггеру .b24-trigger, к которому лоадер
// Битрикса привязал открытие своей формы. Кастомная модалка остаётся в коде, но не всплывает.
(() => {
  'use strict';

  const trigger = document.querySelector('.b24-trigger');
  if (!trigger) return; // триггера нет — тихо выходим, ничего не меняем

  // Тема заявки (data-open-form="Робототехника" и т.п.) в CRM-форму не передаётся:
  // у click-формы Битрикса нет нашего скрытого поля topic. Если понадобится
  // предзаполнение — делается на стороне Битрикса через событие b24:form:init.
  window.openForm = () => trigger.click();
})();
